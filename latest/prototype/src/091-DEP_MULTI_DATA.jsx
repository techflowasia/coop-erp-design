// วันที่ทำการปัจจุบันในรูปแบบไทย dd/mm/พ.ศ. (จาก DEP_OPS_TODAY)
window.depMultiThaiToday = function () {
  const s = window.DEP_OPS_TODAY || '2026-07-21';
  const [y, m, d] = s.split('-').map(Number);
  return `${String(d).padStart(2, '0')}/${String(m).padStart(2, '0')}/${y + 543}`;
};
